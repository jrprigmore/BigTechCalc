const NAVY = [13, 31, 60];
const GOLD = [138, 100, 16];
const GREY = [107, 122, 144];

export function buildPdf(jspdfNS, payload) {
  const { jsPDF } = jspdfNS;
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'letter' });
  const W = doc.internal.pageSize.getWidth();
  const M = 40;
  const usd = (v) => '$' + Math.round(v || 0).toLocaleString('en-US');

  function header(title, sub) {
    doc.setFillColor(...NAVY);
    doc.rect(0, 0, W, 54, 'F');
    doc.setTextColor(240, 237, 230);
    doc.setFont('helvetica', 'bold'); doc.setFontSize(15);
    doc.text('bigtechcalc', M, 26);
    doc.setTextColor(240, 208, 128);
    doc.text('.com', M + doc.getTextWidth('bigtechcalc'), 26);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
    doc.setTextColor(200, 214, 228);
    doc.text(title, M, 41);
    if (sub) doc.text(sub, W - M, 41, { align: 'right' });
  }

  function footer() {
    const n = doc.internal.getNumberOfPages();
    for (let i = 1; i <= n; i++) {
      doc.setPage(i);
      const H = doc.internal.pageSize.getHeight();
      doc.setFontSize(7.5); doc.setTextColor(...GREY);
      doc.text(DISCLAIMER_SHORT, M, H - 20);
      doc.text(`Page ${i} of ${n}  ·  bigtechcalc.com  ·  PEFG, PLLC`, W - M, H - 20, { align: 'right' });
    }
  }

  const dispKey = payload.displayScenario;
  const disp = payload.results[dispKey];
  const scenName = payload.scenarios[dispKey].name;

  /* ---- Page 1: summary ---- */
  header('Total compensation comparison', new Date().toLocaleDateString('en-US', { dateStyle: 'long' }));
  let y = 76;

  doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
  doc.text(`Cumulative gross compensation — ${payload.horizon}-year horizon`, M, y);
  y += 8;

  doc.autoTable({
    startY: y + 6,
    head: [['Offer', 'Scenario', 'Year 1', 'Year 3', 'Year 5', 'Year 10',
            `${payload.horizon}-yr total`, 'Unvested at horizon']],
    body: payload.offers.flatMap((o) =>
      ['conservative', 'medium', 'aggressive'].map((k) => {
        const r = payload.results[k].find((x) => x.offerId === o.id);
        if (!r) return null;
        return [
          r.company + (o.id === payload.baselineId ? ' (baseline)' : ''),
          r.scenarioName, usd(r.cumulativeAt[1]), usd(r.cumulativeAt[3]),
          usd(r.cumulativeAt[5]), usd(r.cumulativeAt[10]),
          usd(r.totalGross), usd(r.unvestedValueAtHorizon),
        ];
      }).filter(Boolean)),
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 4, lineColor: [220, 216, 208] },
    // halign lives in columnStyles, not headStyles — headStyles would
    // override the per-column alignment and right-align the text columns.
    headStyles: { fillColor: NAVY, textColor: [240, 237, 230], fontSize: 7.5 },
    columnStyles: {
      0: { halign: 'left', cellWidth: 130 },
      1: { halign: 'left', cellWidth: 72 },
      2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' },
      5: { halign: 'right' }, 6: { halign: 'right' }, 7: { halign: 'right' },
    },
    margin: { left: M, right: M },
  });

  y = doc.lastAutoTable.finalY + 22;

  doc.setFont('helvetica', 'bold'); doc.setFontSize(11); doc.setTextColor(...NAVY);
  doc.text('Assumptions', M, y);
  const sc = payload.scenarios;
  doc.autoTable({
    startY: y + 6,
    head: [['Lever', 'Conservative', 'Medium', 'Aggressive']],
    body: [
      ['Share price appreciation %/yr', pctStr(sc.conservative.priceAppreciation), pctStr(sc.medium.priceAppreciation), pctStr(sc.aggressive.priceAppreciation)],
      ['Merit increase factor', sc.conservative.meritFactor, sc.medium.meritFactor, sc.aggressive.meritFactor],
      ['Bonus performance multiplier', sc.conservative.bonusMultiplier, sc.medium.bonusMultiplier, sc.aggressive.bonusMultiplier],
      ['Refresher grant growth factor', sc.conservative.refresherGrowthFactor, sc.medium.refresherGrowthFactor, sc.aggressive.refresherGrowthFactor],
      ['Refresher grant years', sc.conservative.refresherYears, sc.medium.refresherYears, sc.aggressive.refresherYears],
    ],
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 4, lineColor: [220, 216, 208] },
    headStyles: { fillColor: [26, 58, 92], textColor: [240, 237, 230], fontSize: 7.5 },
    columnStyles: { 0: { cellWidth: 210 } },
    margin: { left: M, right: M },
  });

  /* ---- Per-offer detail pages ---- */
  for (const res of disp) {
    doc.addPage();
    header(`${res.company} — ${res.scenarioName} scenario`, `${payload.horizon}-year projection`);
    doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
    doc.text(`${res.company}`, M, 76);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...GREY);
    doc.text(`${res.scenarioName} scenario · gross, before tax · ${payload.horizon}-year total ${usd(res.totalGross)}`, M, 90);

    const sum = (k) => res.rows.reduce((a, r) => a + r[k], 0);
    doc.autoTable({
      startY: 102,
      head: [['Year', 'Cal.', 'Share price', 'Base', 'Bonus', 'Sign-on',
              'Initial vest', 'Refresher vest', 'Total gross', 'Cumulative', 'Grants']],
      body: res.rows.map((r) => [
        'Y' + r.yearIndex, r.calendarYear, '$' + r.sharePrice.toFixed(2),
        usd(r.baseSalary), usd(r.bonus), usd(r.signOn),
        usd(r.initialVest), usd(r.refresherVest), usd(r.total), usd(r.cumulative),
        r.concurrentGrants,
      ]),
      foot: [['Total', '', '', usd(sum('baseSalary')), usd(sum('bonus')), usd(sum('signOn')),
              usd(sum('initialVest')), usd(sum('refresherVest')), usd(res.totalGross), '', '']],
      theme: 'grid',
      styles: { fontSize: 8, cellPadding: 3.5, halign: 'right', lineColor: [220, 216, 208] },
      headStyles: { fillColor: NAVY, textColor: [240, 237, 230], fontSize: 7.5 },
      footStyles: { fillColor: [247, 245, 240], textColor: NAVY, fontStyle: 'bold' },
      columnStyles: { 0: { halign: 'left' } },
      margin: { left: M, right: M },
    });

    doc.setFontSize(8); doc.setTextColor(...GOLD);
    doc.text(
      `Unvested at horizon: ${res.unvestedShares.toFixed(2)} shares, ${usd(res.unvestedValueAtHorizon)} at the year-${payload.horizon} projected price. Excluded from the totals above.`,
      M, doc.lastAutoTable.finalY + 16);
  }

  /* ---- Methodology / disclaimer page ---- */
  doc.addPage();
  header('Methodology and limitations', '');
  doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
  doc.text('How these numbers were produced', M, 78);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(60, 70, 90);

  const method = [
    'Grant dollars are converted to a share count at the grant-date share price. Each vesting tranche is then',
    'valued at the projected share price on its vest date. Grant-size growth and share-price appreciation are',
    'modelled as separate inputs, because they are separate things.',
    '',
    'Overlapping refresher grants are held in an explicit ledger with one row per grant and one entry per vest',
    'event. Nothing is computed as a rolling-window sum, so concurrent grants cannot be double-counted or',
    'mis-divided. The "grants vesting" column reports how many distinct grants contribute in each year; on a',
    'four-year schedule with annual refreshers it should reach and then hold at four.',
    '',
    'Currency is accumulated as integer cents throughout, so no floating-point error builds up across the horizon.',
    '',
  ];
  let ly = 96;
  for (const line of method) { doc.text(line, M, ly); ly += 12; }

  doc.setFont('helvetica', 'bold'); doc.setTextColor(...NAVY); doc.setFontSize(11);
  doc.text('Limitations and disclaimer', M, ly + 6); ly += 24;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(60, 70, 90);
  for (const line of DISCLAIMER_LONG) { doc.text(line, M, ly); ly += 11; }

  footer();
  doc.save(`bigtechcalc-comparison-${ts()}.pdf`);
}
