export function buildWorkbook(XLSX, payload) {
  const wb = XLSX.utils.book_new();
  const aoa = (rows) => XLSX.utils.aoa_to_sheet(rows);

  /* ---- README ---- */
  const readme = [
    ['bigtechcalc.com — compensation projection'],
    [],
    [`Generated`, new Date().toISOString()],
    ['Projection horizon', `${payload.horizon} years`],
    ['Comparison alignment', payload.alignment === 'tenure' ? 'Tenure year (Year 1 = each offer\'s own start)' : 'Calendar year'],
    ['Displayed scenario', payload.scenarios[payload.displayScenario].name],
    [],
    ['READ THIS FIRST'],
    ...DISCLAIMER_LONG.map((l) => [l]),
    [],
    ['TABS IN THIS WORKBOOK'],
    ['Scenarios', 'The three scenarios and every lever behind them.'],
    ['Inputs', 'Every offer input, exactly as entered.'],
    ['Summary', 'Cumulative gross at years 1 / 3 / 5 / 10 for each offer in each scenario.'],
    ['<Offer> — <Scenario>', 'Year-by-year detail for the displayed scenario.'],
    ['Tranche Ledger', 'One row per vest event across every offer and scenario. This is the audit trail.'],
  ];
  XLSX.utils.book_append_sheet(wb, aoa(readme), 'README');

  /* ---- Scenarios ---- */
  const sc = payload.scenarios;
  const scenRows = [
    ['GROWTH SCENARIOS'],
    ['Every lever below is a user-set assumption, not a forecast.'],
    ['The medium share-price figure is a long-run broad-market nominal assumption,'],
    ['not a projection for any specific company.'],
    [],
    ['Lever', 'Conservative', 'Medium', 'Aggressive'],
    ['Share price appreciation %/yr', pctStr(sc.conservative.priceAppreciation), pctStr(sc.medium.priceAppreciation), pctStr(sc.aggressive.priceAppreciation)],
    ['Merit increase factor (x offer input)', sc.conservative.meritFactor, sc.medium.meritFactor, sc.aggressive.meritFactor],
    ['Bonus performance multiplier', sc.conservative.bonusMultiplier, sc.medium.bonusMultiplier, sc.aggressive.bonusMultiplier],
    ['Refresher grant growth factor (x offer input)', sc.conservative.refresherGrowthFactor, sc.medium.refresherGrowthFactor, sc.aggressive.refresherGrowthFactor],
    ['Number of refresher grant years', sc.conservative.refresherYears, sc.medium.refresherYears, sc.aggressive.refresherYears],
  ];
  for (const k of ['conservative', 'medium', 'aggressive']) {
    if (sc[k]._wasCapped) {
      scenRows.push([]);
      scenRows.push([`NOTE: ${sc[k].name} appreciation was entered at ${pctStr(sc[k]._uncapped)}/yr and capped to ${pctStr(sc[k].priceAppreciation)}/yr.`]);
    }
  }
  XLSX.utils.book_append_sheet(wb, aoa(scenRows), 'Scenarios');

  /* ---- Inputs ---- */
  const inputHeader = [
    'Company', 'Ticker', 'Private?', 'Baseline?', 'Start year',
    'Base salary', 'Merit %/yr', 'Bonus target %', 'Bonus basis', 'Bonus in year 1?',
    'Sign-on total', 'Sign-on schedule', 'Grant-date price', 'Initial grant value',
    'Initial vest schedule', 'Refresher value', 'First refresher year',
    'Refresher growth %/yr', 'Refresher vest schedule', 'Refresher slots', 'First vest timing',
  ];
  const schedStr = (s) =>
    `${s.granularity}, cliff ${s.cliffPeriods}: ` +
    s.events.map((e) => `p${e.periodIndex}=${(e.percent * 100).toFixed(2)}%`).join(' / ');

  const inputRows = [['OFFER INPUTS, AS ENTERED'], [], inputHeader];
  for (const o of payload.offers) {
    inputRows.push([
      o.company, o.ticker || '', o.isPrivate ? 'yes' : 'no',
      o.id === payload.baselineId ? 'yes' : 'no', o.startYear,
      o.baseSalary, pctStr(o.meritPct), pctStr(o.bonusTargetPct),
      o.bonusBasis === 'prior' ? 'Prior-year base' : 'Current-year base',
      o.bonusInYear1 ? 'yes' : 'no',
      o.signOnTotal, o.signOnSchedule.map((p) => (p * 100).toFixed(0) + '%').join(' / '),
      o.grantPrice, o.initialGrantValue, schedStr(o.initialSchedule),
      o.refresherValue, o.refresherFirstYear, pctStr(o.refresherGrowthPct),
      schedStr(o.refresherSchedule), o.refresherSlots,
      o.firstVestOffsetYears === 1 ? 'Year after grant' : 'In grant year',
    ]);
  }
  XLSX.utils.book_append_sheet(wb, aoa(inputRows), 'Inputs');

  /* ---- Summary ---- */
  const sumRows = [
    ['CUMULATIVE GROSS COMPENSATION'],
    [DISCLAIMER_SHORT],
    [],
    ['Offer', 'Scenario', 'Year 1', 'Year 3', 'Year 5', 'Year 10',
     `Year ${payload.horizon} total`, 'Unvested shares at horizon', 'Unvested value at horizon'],
  ];
  for (const o of payload.offers) {
    for (const k of ['conservative', 'medium', 'aggressive']) {
      const r = payload.results[k].find((x) => x.offerId === o.id);
      if (!r) continue;
      sumRows.push([
        r.company, r.scenarioName,
        r.cumulativeAt[1], r.cumulativeAt[3], r.cumulativeAt[5], r.cumulativeAt[10],
        r.totalGross, Number(r.unvestedShares.toFixed(4)), r.unvestedValueAtHorizon,
      ]);
    }
  }
  XLSX.utils.book_append_sheet(wb, aoa(sumRows), 'Summary');

  /* ---- Per-offer year-by-year, displayed scenario ---- */
  const dispKey = payload.displayScenario;
  for (const res of payload.results[dispKey]) {
    const rows = [
      [`${res.company} — ${res.scenarioName} scenario`],
      [DISCLAIMER_SHORT],
      [],
      ['Year', 'Calendar year', 'Share price', 'Base salary', 'Bonus', 'Sign-on',
       'Initial grant vest', 'Refresher vest', 'Total equity vest',
       'TOTAL GROSS', 'Cumulative gross', 'Concurrent grants vesting'],
    ];
    for (const r of res.rows) {
      rows.push([
        r.yearIndex, r.calendarYear, r.sharePrice, r.baseSalary, r.bonus, r.signOn,
        r.initialVest, r.refresherVest, r.equityVest, r.total, r.cumulative, r.concurrentGrants,
      ]);
    }
    const sum = (k) => res.rows.reduce((a, r) => a + r[k], 0);
    rows.push([]);
    rows.push(['TOTAL', '', '', sum('baseSalary'), sum('bonus'), sum('signOn'),
      sum('initialVest'), sum('refresherVest'), sum('equityVest'), res.totalGross, '', '']);

    // Excel sheet names: 31 chars max, and / \ ? * [ ] are illegal.
    let name = `${res.company} ${res.scenarioName}`.replace(/[\\/?*[\]:]/g, '-').slice(0, 31);
    let n = 2;
    while (wb.SheetNames.includes(name)) name = (name.slice(0, 28) + ' ' + n++).slice(0, 31);
    XLSX.utils.book_append_sheet(wb, aoa(rows), name);
  }

  /* ---- Tranche ledger ---- */
  const ledRows = [
    ['EQUITY TRANCHE LEDGER — one row per vest event'],
    ['Overlapping refreshers appear as separate concurrent grants, not a rolling-window sum.'],
    [],
    ['Offer', 'Scenario', 'Source grant', 'Grant year', 'Grant value', 'Grant-date price',
     'Shares granted', 'Vest calendar year', 'Vest fractional year', 'Vest %',
     'Shares vesting', 'Price at vest', 'Value at vest', 'Within horizon'],
  ];
  for (const k of ['conservative', 'medium', 'aggressive']) {
    for (const res of payload.results[k]) {
      for (const t of res.ledger) {
        ledRows.push([
          res.company, res.scenarioName, t.grantLabel, t.grantYear, t.grantValue,
          t.grantPrice, Number(t.grantShares.toFixed(6)), t.vestCalendarYear,
          t.vestFractionalYear, Number((t.vestPercent * 100).toFixed(4)),
          Number(t.shares.toFixed(6)), t.priceUsed, t.value, t.withinHorizon ? 'yes' : 'no',
        ]);
      }
    }
  }
  XLSX.utils.book_append_sheet(wb, aoa(ledRows), 'Tranche Ledger');

  XLSX.writeFile(wb, `bigtechcalc-comparison-${ts()}.xlsx`);
}

