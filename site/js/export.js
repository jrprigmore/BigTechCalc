export function buildCsv(payload) {
  const rows = [];
  rows.push(['bigtechcalc.com — equity tranche ledger']);
  rows.push([DISCLAIMER_SHORT]);
  rows.push([`Generated ${new Date().toISOString()}`, `Horizon ${payload.horizon} years`]);
  rows.push([]);
  rows.push([
    'Offer', 'Scenario', 'Source grant', 'Grant year', 'Grant value',
    'Grant-date price', 'Shares granted', 'Vest calendar year',
    'Vest fractional year', 'Vest %', 'Shares vesting', 'Price at vest',
    'Value at vest', 'Within horizon',
  ]);

  for (const scenKey of ['conservative', 'medium', 'aggressive']) {
    for (const res of payload.results[scenKey]) {
      for (const t of res.ledger) {
        rows.push([
          res.company, res.scenarioName, t.grantLabel, t.grantYear,
          t.grantValue.toFixed(2), t.grantPrice.toFixed(2),
          t.grantShares.toFixed(6), t.vestCalendarYear,
          t.vestFractionalYear, (t.vestPercent * 100).toFixed(4),
          t.shares.toFixed(6), t.priceUsed.toFixed(2),
          t.value.toFixed(2), t.withinHorizon ? 'yes' : 'no',
        ]);
      }
    }
  }

  const esc = (v) => {
    const s = String(v ?? '');
    return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
  };
  const csv = rows.map((r) => r.map(esc).join(',')).join('\r\n');
  saveBlob(new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8' }),
    `bigtechcalc-tranche-ledger-${ts()}.csv`);
}

