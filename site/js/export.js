/*
 * bigtechcalc.com — export module
 *
 * PDF, XLSX and CSV. All three are free and ungated. Libraries are
 * loaded lazily by app.js only when the user clicks an export button,
 * so they never affect first paint or Core Web Vitals.
 *
 * Every export carries the gross/pre-tax disclaimer. That is not
 * decoration — the numbers are wrong if a reader assumes otherwise.
 */

const DISCLAIMER_SHORT =
  'All figures are GROSS, before any tax. RSUs are ordinary income at vest, at the vest-date price.';

const DISCLAIMER_LONG = [
  'This is a modelling tool, not financial advice.',
  '',
  'All figures are GROSS and exclude all taxes. RSUs are taxed as ordinary income at vest, valued at the',
  'vest-date share price, and are typically subject to statutory supplemental withholding that may sit below',
  'your marginal rate. Your take-home will be materially lower than the totals shown.',
  '',
  'Projections are arithmetic consequences of the assumptions listed in this file. They are not predictions.',
  'Past share price performance does not indicate future results. The share price path is a constant compound',
  'rate with no volatility; real prices are not smooth, and the sequence of returns matters when tranches vest',
  'on fixed dates.',
  '',
  'Not modelled: taxes, cost-of-living or relocation differences, 401(k) match, ESPP, or benefits.',
  '',
  'Vesting schedule templates in this tool are editable examples. They are not statements of any named',
  "employer's current equity policy. Enter the terms in your own offer letter.",
  '',
  'Generated by bigtechcalc.com — PEFG, PLLC.',
];

function ts() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

function saveBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function pctStr(v) { return (v * 100).toFixed(2).replace(/\.00$/, '') + '%'; }

